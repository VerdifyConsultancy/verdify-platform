def test_remediation_rejects_untrusted_report_fields_without_echoing_them(tmp_path):
    excluded = next(iter(policy.PUBLIC_CROP_EXCLUDE_SLUGS))
    encoded = "".join(f"%{byte:02X}" for byte in excluded.encode())
    root = tmp_path / "content"
    root.mkdir()
    report = tmp_path / "report.json"
    manifest = tmp_path / "manifest.json"
    _write_scanner_report(
        report,
        root,
        [{"path": f"plans/{encoded}.md", "route": f"/plans/{encoded}", "reason": f"unknown-{encoded}"}],
    )

    proc = _run(REMEDIATE, "--report", report, "--root", root, "--manifest", manifest)

    output = proc.stdout + proc.stderr
    assert proc.returncode == 2
    assert not manifest.exists()
    assert excluded not in output.casefold()
    assert encoded.casefold() not in output.casefold()
    assert "unknown-" not in output


