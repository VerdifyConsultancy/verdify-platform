def test_remediation_rejects_same_root_final_and_intermediate_symlinks(tmp_path):
    excluded = next(iter(policy.PUBLIC_CROP_EXCLUDE_SLUGS))
    for link_kind, date in (("final", "2026-07-06"), ("intermediate", "2026-07-07")):
        case = tmp_path / link_kind
        root = case / "content"
        real_plans = root / "real-plans"
        real_plans.mkdir(parents=True)
        target = real_plans / f"{date}.md"
        original = f"{GENERATED_MARKER}\nGenerated {excluded} note.\n"
        target.write_text(original, encoding="utf-8")
        if link_kind == "final":
            plans = root / "plans"
            plans.mkdir()
            (plans / f"{date}.md").symlink_to(target)
        else:
            (root / "plans").symlink_to(real_plans, target_is_directory=True)
        report = case / "report.json"
        manifest = case / "manifest.json"
        _write_scanner_report(
            report,
            root,
            [{"path": f"plans/{date}.md", "route": f"/plans/{date}", "reason": "content"}],
        )

        applied = _run(
            REMEDIATE,
            "--report",
            report,
            "--root",
            root,
            "--manifest",
            manifest,
            "--apply-redaction",
        )

        assert applied.returncode == 0, applied.stderr
        assert target.read_text(encoding="utf-8") == original
        item = json.loads(manifest.read_text(encoding="utf-8"))["items"][0]
        assert item["action"] == "resolve_source_content"
        assert item["route"] == f"/plans/{date}"
        assert item["reason_classes"] == ["protected-reference"]
        assert item["automatic_redaction_eligible"] is False
        assert item["redaction_applied"] is False


