from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

from verdify_public import output_policy as policy

REPO_ROOT = Path(__file__).resolve().parents[1]
GUARD = REPO_ROOT / "scripts" / "check-public-output.py"
REMEDIATE = REPO_ROOT / "scripts" / "remediate-public-output.py"
GENERATED_MARKER = "[//]: # (auto-generated by scripts/generate-daily-plan.py; fixture)"


def _run(*args: object) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, *map(str, args)],
        capture_output=True,
        text=True,
        check=False,
    )


def _root_identity(root: Path) -> str:
    metadata = root.stat()
    material = f"public-output-root-v1:{metadata.st_dev}:{metadata.st_ino}".encode()
    return hashlib.sha256(material).hexdigest()


def _write_scanner_report(path: Path, root: Path, findings: list[dict[str, str]]) -> None:
    label = policy.redact_non_public_crop_references(root.name)
    identity = _root_identity(root)
    normalized = [
        {
            "root": label,
            "root_identity": identity,
            "path": finding["path"],
            "route": finding["route"],
            "reason": finding["reason"],
        }
        for finding in findings
    ]
    path.write_text(
        json.dumps(
            {
                "schema_version": 2,
                "roots": [{"label": label, "identity": identity}],
                "missing_roots": [],
                "routes": sorted({finding["route"] for finding in normalized}),
                "findings": normalized,
            }
        ),
        encoding="utf-8",
    )


def test_remediation_manifest_targets_only_marker_verified_historical_plans(tmp_path):
    excluded = next(iter(policy.PUBLIC_CROP_EXCLUDE_SLUGS))
    root = tmp_path / "content"
    plans = root / "plans"
    plans.mkdir(parents=True)
    generated = plans / "2026-07-03.md"
    generated.write_text(f"{GENERATED_MARKER}\nGenerated {excluded} note.\n", encoding="utf-8")
    handwritten = plans / "2026-07-04.md"
    handwritten.write_text(f"Handwritten {excluded} note.\n", encoding="utf-8")
    invalid = plans / "2026-07-05.md"
    invalid.write_text(f"{GENERATED_MARKER}\nCost: USD NaN\n", encoding="utf-8")
    report = tmp_path / "report.json"
    manifest = tmp_path / "manifest.json"

    guard = _run(GUARD, "--root", root, "--json-report", report)
    assert guard.returncode == 1
    dry_run = _run(REMEDIATE, "--report", report, "--root", root, "--manifest", manifest)

    assert dry_run.returncode == 0, dry_run.stderr
    payload = json.loads(manifest.read_text(encoding="utf-8"))
    by_date = {item["date"]: item for item in payload["items"]}
    assert by_date["2026-07-03"]["automatic_redaction_eligible"] is True
    assert by_date["2026-07-03"]["reason_classes"] == ["protected-reference"]
    assert by_date["2026-07-03"]["regenerate_command"] == [
        "python3",
        "scripts/generate-daily-plan.py",
        "--date",
        "2026-07-03",
    ]
    assert by_date["2026-07-04"]["action"] == "resolve_source_content"
    assert by_date["2026-07-05"]["action"] == "regenerate_generated_plan"
    assert excluded in generated.read_text(encoding="utf-8").casefold()


