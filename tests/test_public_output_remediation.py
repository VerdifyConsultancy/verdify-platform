def test_remediation_rejects_duplicate_nonfinite_oversized_and_hardlinked_reports(tmp_path):
    root = tmp_path / "content"
    root.mkdir()
    manifest = tmp_path / "manifest.json"
    cases = {
        "duplicate.json": '{"schema_version":2,"schema_version":2}\n',
        "nonfinite.json": '{"schema_version":NaN}\n',
    }
    for name, content in cases.items():
        report = tmp_path / name
        report.write_text(content, encoding="utf-8")
        proc = _run(REMEDIATE, "--report", report, "--root", root, "--manifest", manifest)
        assert proc.returncode == 2
        assert proc.stderr.strip() == "public-output remediation: invalid scanner report"
        assert not manifest.exists()

    oversized = tmp_path / "oversized.json"
    with oversized.open("wb") as report_file:
        report_file.truncate(8 * 1024 * 1024 + 1)
    proc = _run(REMEDIATE, "--report", oversized, "--root", root, "--manifest", manifest)
    assert proc.returncode == 2
    assert not manifest.exists()

    original = tmp_path / "report-original.json"
    original.write_text("{}", encoding="utf-8")
    linked = tmp_path / "report-linked.json"
    os.link(original, linked)
    proc = _run(REMEDIATE, "--report", linked, "--root", root, "--manifest", manifest)
    assert proc.returncode == 2
    assert not manifest.exists()


def test_remediation_rejects_hardlinked_source_and_reports_manifest_write_failure_generically(tmp_path):
    excluded = next(iter(policy.PUBLIC_CROP_EXCLUDE_SLUGS))
    root = tmp_path / "content"
    plans = root / "plans"
    plans.mkdir(parents=True)
    source = plans / "2026-07-11.md"
    original = f"{GENERATED_MARKER}\nGenerated {excluded} note.\n"
    source.write_text(original, encoding="utf-8")
    os.link(source, plans / "alias.md")
    report = tmp_path / "report.json"
    assert _run(GUARD, "--root", root, "--json-report", report).returncode == 1
    manifest = tmp_path / "manifest.json"

    proc = _run(
        REMEDIATE,
        "--report",
        report,
        "--root",
        root,
        "--manifest",
        manifest,
        "--apply-redaction",
    )

    assert proc.returncode == 0
    assert source.read_text(encoding="utf-8") == original
    assert all(not item["redaction_applied"] for item in json.loads(manifest.read_text())["items"])

    manifest_directory = tmp_path / "private-manifest-name"
    manifest_directory.mkdir()
    write_failure = _run(
        REMEDIATE,
        "--report",
        report,
        "--root",
        root,
        "--manifest",
        manifest_directory,
    )
    assert write_failure.returncode == 2
    assert write_failure.stderr.strip() == "public-output remediation: manifest write failed"
    assert manifest_directory.name not in write_failure.stderr


def test_remediation_does_not_open_source_files_over_the_fixed_size_limit(tmp_path):
    excluded = next(iter(policy.PUBLIC_CROP_EXCLUDE_SLUGS))
    root = tmp_path / "content"
    plans = root / "plans"
    plans.mkdir(parents=True)
    source = plans / "2026-07-12.md"
    prefix = f"{GENERATED_MARKER}\nGenerated {excluded} note.\n".encode()
    source.write_bytes(prefix)
    with source.open("r+b") as source_file:
        source_file.truncate(16 * 1024 * 1024 + 1)
    report = tmp_path / "report.json"
    manifest = tmp_path / "manifest.json"
    assert _run(GUARD, "--root", root, "--json-report", report).returncode == 1

    proc = _run(
        REMEDIATE,
        "--report",
        report,
        "--root",
        root,
        "--manifest",
        manifest,
        "--apply-redaction",
    )

    assert proc.returncode == 0
    assert source.read_bytes()[: len(prefix)] == prefix
    item = json.loads(manifest.read_text(encoding="utf-8"))["items"][0]
    assert item["automatic_redaction_eligible"] is False
    assert item["redaction_applied"] is False
