def render(path=SOURCE):
    return [x for x in yaml.safe_load_all(subprocess.check_output(["kustomize", "build", str(path)], text=True)) if x]


@pytest.fixture(scope="module")
def rendered():
    return render()


def one(rendered, kind, name=None):
    found = [x for x in rendered if x["kind"] == kind and name in (None, x["metadata"]["name"])]
    assert len(found) == 1, (kind, name, [x["metadata"]["name"] for x in found])
    return found[0]


def pod_spec(rendered):
    return one(rendered, "Deployment", WEB)["spec"]["template"]["spec"]


def env_from(rendered):
    return [ref["configMapRef"]["name"] for ref in pod_spec(rendered)["containers"][0]["envFrom"]]


def selected(selector, labels):
    for expression in selector.get("matchExpressions", []):
        key, operator, values = expression["key"], expression["operator"], expression.get("values", [])
        if operator == "In":
            matched = labels.get(key) in values
        elif operator == "NotIn":
            matched = labels.get(key) not in values
        elif operator == "Exists":
            matched = key in labels
        elif operator == "DoesNotExist":
            matched = key not in labels
        else:
            raise AssertionError(f"review selector operator {operator}")
        if not matched:
            return False
    return all(labels.get(key) == value for key, value in selector.get("matchLabels", {}).items())


def admitted(rendered, pod_labels, source_namespace, source_labels, port, protocol="TCP"):
    """NetworkPolicy ingress semantics for a pod in verdify-dashboard; there is no ipBlock peer here."""
    policies = [x for x in rendered if x["kind"] == "NetworkPolicy" and "Ingress" in x["spec"]["policyTypes"]]
    governing = [p for p in policies if selected(p["spec"]["podSelector"], pod_labels)]
    if not governing:
        return True
    for policy in governing:
        for rule in policy["spec"].get("ingress", []):
            ports = rule.get("ports", [])
            if ports and not any(p["port"] == port and p.get("protocol", "TCP") == protocol for p in ports):
                continue
            peers = rule.get("from", [])
            if not peers:
                return True
            for peer in peers:
                assert "ipBlock" not in peer, "review ipBlock ingress peers"
                if "namespaceSelector" in peer:
                    in_namespace = selected(
                        peer["namespaceSelector"], {"kubernetes.io/metadata.name": source_namespace}
                    )
                else:
                    in_namespace = source_namespace == NAMESPACE
                if in_namespace and selected(peer.get("podSelector", {}), source_labels):
                    return True
    return False


def test_render_has_only_the_appproject_kinds_and_no_secret(rendered):
    assert not [x for x in rendered if x["kind"] == "Secret"]
    assert {(x["apiVersion"], x["kind"]) for x in rendered} <= APPPROJECT_KINDS
    assert one(rendered, "Namespace")["metadata"]["name"] == NAMESPACE
    for x in rendered:
        if x["kind"] != "Namespace":
            assert x["metadata"]["namespace"] == NAMESPACE, (x["kind"], x["metadata"]["name"])


def test_namespace_enforces_the_restricted_profile_as_verdify_prod_does(rendered):
    def pod_security(labels):
        return {k: v for k, v in labels.items() if k.startswith("pod-security.kubernetes.io/")}

    prod = yaml.safe_load(PROD_NAMESPACE.read_text())["metadata"]["labels"]
    assert (
        pod_security(one(rendered, "Namespace")["metadata"]["labels"])
        == pod_security(prod)
        == {
            "pod-security.kubernetes.io/enforce": "restricted",
            "pod-security.kubernetes.io/enforce-version": "latest",
            "pod-security.kubernetes.io/warn": "restricted",
        }
    )


def test_writes_flag_lives_in_the_generated_hash_suffixed_configmap(rendered):
    config = one(rendered, "ConfigMap")
    assert re.fullmatch(WEB + r"-[a-z0-9]{10}", config["metadata"]["name"])
    assert config["metadata"]["annotations"] == {"argocd.argoproj.io/compare-options": "IgnoreExtraneous"}
    data = dict(config["data"])
    # R2 (#1144) and the rollback flip the flag in one-line PRs, so only its two values are pinned here.
    assert data.pop("DASHBOARD_WRITES_ENABLED") in {"false", "true"}
    assert data == {
        "PUBLIC_ORIGIN": "https://dashboard.verdify.ai",
        "OIDC_ISSUER": "https://auth.vallery.net/application/o/verdify-dashboard/",
        "OIDC_CLIENT_ID": "verdify-dashboard",
        "OPERATOR_API_URL": "http://verdify-operator-api.verdify-prod.svc:8090",
    }
    assert env_from(rendered) == [config["metadata"]["name"]]


def test_changing_the_writes_flag_renames_the_configmap_the_deployment_reads(rendered, tmp_path):
    current = one(rendered, "ConfigMap")["data"]["DASHBOARD_WRITES_ENABLED"]
    flipped = {"false": "true", "true": "false"}[current]
    shutil.copytree(SOURCE, tmp_path / "dashboard")
    kustomization = tmp_path / "dashboard/kustomization.yaml"
    line = f"      - DASHBOARD_WRITES_ENABLED={current}\n"
    text = kustomization.read_text()
    assert text.count(line) == 1
    kustomization.write_text(text.replace(line, f"      - DASHBOARD_WRITES_ENABLED={flipped}\n"))

    changed = render(tmp_path / "dashboard")
    config = one(changed, "ConfigMap")
    assert config["data"]["DASHBOARD_WRITES_ENABLED"] == flipped
    assert config["metadata"]["annotations"] == {"argocd.argoproj.io/compare-options": "IgnoreExtraneous"}
    assert env_from(changed) == [config["metadata"]["name"]] != env_from(rendered)


def test_web_runs_no_pod_until_its_digest_is_pinned(rendered):
    deployment = one(rendered, "Deployment", WEB)
    (container,) = deployment["spec"]["template"]["spec"]["containers"]
    repository, _, digest = container["image"].partition("@")
    assert repository == REPOSITORY
    # Replicas 0 and no digest until R1's pin PR (#1143) sets the first digest and count 1.
    pinned = re.fullmatch(r"sha256:[0-9a-f]{64}", digest) is not None
    assert pinned or not digest
    assert (deployment["spec"]["replicas"], pinned) in {(0, False), (1, True)}


