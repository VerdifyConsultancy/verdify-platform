def test_tier1_forwarder_excludes_every_dashboard_host(rendered):
    hosts = set(re.findall(r"Host\(`([^`]+)`\)", one(rendered, "IngressRoute", WEB)["spec"]["routes"][0]["match"]))
    assert hosts == {"dashboard.verdify.ai"}
    match = yaml.safe_load(TIER1.read_text())["spec"]["routes"][0]["match"]
    expression = re.search(r"HostRegexp\(`([^`]+)`\)", match).group(1)
    excluded = set(re.findall(r"!Host\(`([^`]+)`\)", match))
    for host in hosts:
        # The priority-50 HostRegexp matches the host, so only the exclusion keeps it off tier-1.
        assert re.fullmatch(expression, host) and host in excluded, host


