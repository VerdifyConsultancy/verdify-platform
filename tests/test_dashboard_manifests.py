def test_ingress_admits_only_the_traefik_apps_pods_on_3000(rendered):
    allow = one(rendered, "NetworkPolicy", "allow-web-from-traefik-apps")
    assert allow["spec"]["podSelector"] == {"matchLabels": {"app.kubernetes.io/name": WEB}}
    assert allow["spec"]["ingress"] == [
        {
            "from": [
                {
                    "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "traefik-apps"}},
                    "podSelector": {"matchLabels": TRAEFIK_APPS},
                }
            ],
            "ports": [{"protocol": "TCP", "port": 3000}],
        }
    ]
    deny = one(rendered, "NetworkPolicy", "default-deny-ingress")
    assert deny["spec"] == {"podSelector": {}, "policyTypes": ["Ingress"]}

    assert admitted(rendered, WEB_LABELS, "traefik-apps", TRAEFIK_APPS, 3000)
    for port, protocol in [(3000, "UDP"), (8080, "TCP"), (8090, "TCP"), (9000, "TCP")]:
        assert not admitted(rendered, WEB_LABELS, "traefik-apps", TRAEFIK_APPS, port, protocol), (port, protocol)
    for namespace, labels in [
        ("traefik-apps", {"app.kubernetes.io/name": "traefik"}),
        ("traefik-apps", {"app.kubernetes.io/name": "cloudflared"}),
        ("verdify-prod", TRAEFIK_APPS),
        ("observability", {"app.kubernetes.io/name": "prometheus"}),
        (NAMESPACE, WEB_LABELS),
        ("cloudflare-edge", {"app.kubernetes.io/name": "cloudflared"}),
    ]:
        assert not admitted(rendered, WEB_LABELS, namespace, labels, 3000), (namespace, labels)
    # Any other pod in the namespace stays behind the default deny.
    assert not admitted(rendered, {"app.kubernetes.io/name": "other"}, "traefik-apps", TRAEFIK_APPS, 3000)
