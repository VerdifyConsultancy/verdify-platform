#!/usr/bin/env python3
"""One-time repair of legacy lab content generated before f17e30f (2026-07-12).

The commit that added scripts/check-public-output.py ALSO fixed the two
generator defects the guard detects (non-public crop redaction in
public_text(), and the `USD None` currency rendering). Production's publisher
image was never advanced past 2026-07-11, so 13 days of content was generated
by the pre-fix generator and published with no guard. The guard now fails
closed on its own predecessor's output, and publish-site-content.sh only
regenerates PREV_DATE/DATE, so the backlog can never heal itself.

This repairs the durable S3 content corpus in place so the corpus matches what
the fixed generator emits:

  1. `, and USD None total resource cost` -> removed. The fixed generator
     appends the cost clause only when cost["total"] is not None, which is
     exactly what the 2026-07-26/27 pages (regenerated by the fixed generator)
     already show.
  2. Non-public crop references -> redacted with the repo's own
     verdify_public.redact_non_public_crop_references, the same function
     public_text() applies.
  3. PNG `cICP` chunks stripped. cICP is a standard but post-2022 chunk that
     macOS screenshots emit; it is not in the guard's safe-ancillary
     whitelist, so those screenshots are unpublishable. Colour rendering is
     preserved by the iCCP profile present in all three files. The durable fix
     is whitelisting cICP in the guard; this unblocks the corpus meanwhile.

Idempotent: a second run reports 0 changes.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

sys.path.insert(0, "/app")

from verdify_public import redact_non_public_crop_references  # noqa: E402
from verdify_public.output_policy import PUBLIC_CROP_REFERENCE_RE  # noqa: E402

COST_CLAUSE = ", and USD None total resource cost"
TEXT_SUFFIXES = {".md", ".json", ".csv", ".txt", ".xml", ".html"}
STRIP_PNG_CHUNKS = {b"cICP"}


def repair_text(path: Path) -> list[str]:
    original = path.read_text(encoding="utf-8", errors="strict")
    text = original
    changes: list[str] = []

    if COST_CLAUSE in text:
        count = text.count(COST_CLAUSE)
        text = text.replace(COST_CLAUSE, "")
        changes.append(f"dropped {count} unresolved-cost clause(s)")

    if PUBLIC_CROP_REFERENCE_RE.search(text):
        count = len(PUBLIC_CROP_REFERENCE_RE.findall(text))
        text = redact_non_public_crop_references(text)
        changes.append(f"redacted {count} non-public crop reference(s)")

    if text != original:
        path.write_text(text, encoding="utf-8")
    return changes


def repair_png(path: Path) -> list[str]:
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        return []

    out = bytearray(data[:8])
    offset = 8
    stripped: list[str] = []
    while offset + 8 <= len(data):
        length = struct.unpack(">I", data[offset : offset + 4])[0]
        chunk_type = data[offset + 4 : offset + 8]
        end = offset + 12 + length
        if end > len(data):
            # Truncated tail: leave the file untouched rather than guess.
            return []
        if chunk_type in STRIP_PNG_CHUNKS:
            stripped.append(chunk_type.decode("latin-1"))
        else:
            out += data[offset:end]
        offset = end
        if chunk_type == b"IEND":
            break

    if not stripped:
        return []
    path.write_bytes(bytes(out))
    return [f"stripped PNG chunk(s): {', '.join(stripped)}"]


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: repair-legacy-lab-content.py CONTENT_ROOT", file=sys.stderr)
        return 2
    root = Path(sys.argv[1])
    if not root.is_dir():
        print(f"content root is not a directory: {root}", file=sys.stderr)
        return 2

    changed = 0
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        suffix = path.suffix.lower()
        try:
            if suffix in TEXT_SUFFIXES:
                changes = repair_text(path)
            elif suffix == ".png":
                changes = repair_png(path)
            else:
                continue
        except UnicodeDecodeError:
            continue
        if changes:
            changed += 1
            print(f"  {path.relative_to(root)}: {'; '.join(changes)}")

    print(f"repaired {changed} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
