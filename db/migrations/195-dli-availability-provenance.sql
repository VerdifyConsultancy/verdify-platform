);

CREATE OR REPLACE FUNCTION public.fn_dli_validity(
    p_ts timestamptz DEFAULT now(),
    p_greenhouse_id text DEFAULT 'vallery'
)
RETURNS TABLE (
    availability text,
    unavailable_reason text,
    provenance text,
    validity_revision text,
    valid_from timestamptz,
    valid_to timestamptz,
    operator_validated boolean
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        v.availability,
        v.unavailable_reason,
        v.provenance,
        v.validity_revision,
        v.valid_from,
        v.valid_to,
        v.operator_validated
    FROM public.dli_validity_intervals v
    WHERE v.greenhouse_id = p_greenhouse_id
      AND p_ts >= v.valid_from
      AND (v.valid_to IS NULL OR p_ts < v.valid_to)
    ORDER BY v.valid_from DESC
    LIMIT 1
$$;

COMMENT ON FUNCTION public.fn_dli_validity(timestamptz, text) IS
'Returns the one half-open validity interval governing interior crop DLI at a timestamp. No row means no validated DLI contract exists.';

-- This is the only view allowed to expose the old numeric proxy.  Its name and
-- evidence_class make the invalidity explicit; product consumers use
-- v_dli_current/v_dli_daily instead.
CREATE OR REPLACE VIEW public.v_dli_forensic_history AS
SELECT
    c.ts,
    COALESCE(c.greenhouse_id, 'vallery') AS greenhouse_id,
    c.dli_today AS forensic_proxy_dli_mol_m2_day,
    'forensic_invalid_proxy'::text AS evidence_class,
    COALESCE(v.availability, 'unavailable') AS availability,
    COALESCE(v.unavailable_reason, 'validity_contract_missing') AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to
FROM public.climate c
LEFT JOIN LATERAL public.fn_dli_validity(
    c.ts,
    COALESCE(c.greenhouse_id, 'vallery')
) v ON true
WHERE c.dli_today IS NOT NULL;

COMMENT ON VIEW public.v_dli_forensic_history IS
'Forensic-only legacy DLI proxy history. Numeric values came from an invalid interior sensor/exterior proxy/fixture estimate and must never be used as measured crop DLI.';

CREATE OR REPLACE VIEW public.v_dli_current AS
WITH latest AS (
    SELECT DISTINCT ON (COALESCE(c.greenhouse_id, 'vallery'))
        c.ts,
        COALESCE(c.greenhouse_id, 'vallery') AS greenhouse_id,
        c.dli_today AS forensic_proxy_dli_mol_m2_day
    FROM public.climate c
    ORDER BY COALESCE(c.greenhouse_id, 'vallery'), c.ts DESC
)
SELECT
    l.ts,
    l.greenhouse_id,
    CASE
        WHEN v.availability = 'available' AND v.operator_validated
        THEN l.forensic_proxy_dli_mol_m2_day
        ELSE NULL
    END::double precision AS crop_dli_mol_m2_day,
    COALESCE(v.availability, 'unavailable') AS availability,
    COALESCE(v.unavailable_reason, 'validity_contract_missing') AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to,
    (l.forensic_proxy_dli_mol_m2_day IS NOT NULL) AS forensic_proxy_present
FROM latest l
LEFT JOIN LATERAL public.fn_dli_validity(l.ts, l.greenhouse_id) v ON true;

COMMENT ON VIEW public.v_dli_current IS
'Current interior crop DLI product contract. Numeric value is NULL unless an operator-validated interval governs the source; invalid legacy proxy presence is diagnostic-only.';

CREATE OR REPLACE VIEW public.v_dli_daily AS
WITH day_bounds AS (
    SELECT
        ds.date,
        COALESCE(ds.greenhouse_id, 'vallery') AS greenhouse_id,
        ds.dli_final AS forensic_proxy_dli_mol_m2_day,
        ds.date::timestamp AT TIME ZONE 'America/Denver' AS day_start,
        (ds.date + 1)::timestamp AT TIME ZONE 'America/Denver' AS day_end
    FROM public.daily_summary ds
    WHERE ds.date IS NOT NULL
)
SELECT
    d.date,
    d.greenhouse_id,
    CASE
        WHEN v.availability = 'available'
         AND v.operator_validated
         AND v.valid_from <= d.day_start
         AND (v.valid_to IS NULL OR v.valid_to >= d.day_end)
        THEN d.forensic_proxy_dli_mol_m2_day
        ELSE NULL
    END::double precision AS crop_dli_mol_m2_day,
    CASE
        WHEN v.availability = 'available'
         AND v.operator_validated
         AND v.valid_from <= d.day_start
         AND (v.valid_to IS NULL OR v.valid_to >= d.day_end)
        THEN 'available'
        ELSE 'unavailable'
    END::text AS availability,
    CASE
        WHEN v.availability = 'available'
         AND v.operator_validated
         AND v.valid_from <= d.day_start
         AND (v.valid_to IS NULL OR v.valid_to >= d.day_end)
        THEN NULL
        WHEN v.availability = 'available'
        THEN 'validity_interval_does_not_cover_full_local_day'
        ELSE COALESCE(v.unavailable_reason, 'validity_contract_missing')
    END::text AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to,
    (d.forensic_proxy_dli_mol_m2_day IS NOT NULL) AS forensic_proxy_present
FROM day_bounds d
LEFT JOIN LATERAL public.fn_dli_validity(
    d.day_start + interval '12 hours',
    d.greenhouse_id
) v ON true;

COMMENT ON VIEW public.v_dli_daily IS
'Daily interior crop DLI product contract. A numeric value requires one operator-validated interval to cover the entire Denver-local day; partial/boundary days remain unavailable.';

COMMENT ON COLUMN public.climate.dli_today IS
'LEGACY FORENSIC PROXY ONLY while dli-validity-v1 is unavailable. Built from a broken interior sensor/exterior proxy plus fixture estimate; use v_dli_current or v_dli_daily for product truth.';
COMMENT ON COLUMN public.daily_summary.dli_final IS
'LEGACY FORENSIC DAILY PROXY ONLY while dli-validity-v1 is unavailable. Preserved for audit; use v_dli_daily.crop_dli_mol_m2_day for product truth.';

COMMENT ON VIEW public.v_climate_latest IS
'Raw/latest climate transport view. dli_today is the explicitly invalid legacy proxy described by the source-column comment; product consumers must use v_dli_current.';
COMMENT ON MATERIALIZED VIEW public.v_climate_merged IS
'Raw merged climate transport history. dli_today is the explicitly invalid legacy proxy described by the source-column comment; product consumers must use v_dli_daily.';
COMMENT ON VIEW public.v_greenhouse_state IS
'Replay/raw control-state history. dli_today is preserved as forensic legacy proxy only; it is not product DLI. Product consumers must use v_dli_current/v_dli_daily.';

CREATE OR REPLACE VIEW public.v_greenhouse_now AS
SELECT
    c.ts,
    round(c.temp_avg::numeric, 1) AS temp_avg,
    round(c.temp_north::numeric, 1) AS temp_north,
    round(c.temp_south::numeric, 1) AS temp_south,
    round(c.temp_east::numeric, 1) AS temp_east,
    round(c.temp_west::numeric, 1) AS temp_west,
    round(c.rh_avg::numeric, 1) AS rh_avg,
    round(c.vpd_avg::numeric, 2) AS vpd_avg,
    round(c.co2_ppm::numeric, 0) AS co2_ppm,
    round(c.lux::numeric, 0) AS lux,
    round(dc.crop_dli_mol_m2_day::numeric, 2) AS dli_today,
    o.outdoor_temp_f,
    o.outdoor_rh_pct,
    o.wind_mph,
    o.pressure_hpa,
    round(c.mister_water_today::numeric, 1) AS mister_water_today,
    h.hydro_ph,
    h.hydro_ec_us_cm,
    h.hydro_tds_ppm,
    h.hydro_water_temp_f,
    d.wifi_rssi,
    round(d.heap_bytes::numeric, 0) AS heap_kb,
    round(d.uptime_s::numeric, 0) AS uptime_s,
    (
        SELECT s.value
        FROM public.system_state s
        WHERE s.entity = 'greenhouse_state'
        ORDER BY s.ts DESC
        LIMIT 1
    ) AS state,
    (
        SELECT s.value
        FROM public.system_state s
        WHERE s.entity = 'lead_fan'
        ORDER BY s.ts DESC
        LIMIT 1
    ) AS lead_fan,
    public.fn_system_health() AS health_score,
    (
        SELECT count(*)
        FROM public.alert_log a
        WHERE a.disposition = 'open'
    ) AS open_alerts,
    cost.cost_electric,
    cost.cost_gas,
    cost.cost_water,
    cost.cost_total,
    dc.availability AS dli_availability,
    dc.unavailable_reason AS dli_unavailable_reason,
    dc.provenance AS dli_provenance,
    dc.validity_revision AS dli_validity_revision,
    dc.valid_from AS dli_valid_from,
    dc.valid_to AS dli_valid_to
FROM public.climate c
LEFT JOIN LATERAL (
    SELECT d0.wifi_rssi, d0.heap_bytes, d0.uptime_s
    FROM public.diagnostics d0
    ORDER BY d0.ts DESC
    LIMIT 1
) d ON true
LEFT JOIN LATERAL (
    SELECT
        round(c0.outdoor_temp_f::numeric, 1) AS outdoor_temp_f,
        round(c0.outdoor_rh_pct::numeric, 0) AS outdoor_rh_pct,
        round(c0.wind_speed_mph::numeric, 1) AS wind_mph,
        round(c0.pressure_hpa::numeric, 1) AS pressure_hpa
    FROM public.climate c0
    WHERE c0.outdoor_temp_f IS NOT NULL
      AND c0.ts > now() - interval '30 minutes'
    ORDER BY c0.ts DESC
    LIMIT 1
) o ON true
LEFT JOIN LATERAL (
    SELECT
        round(c1.hydro_ph::numeric, 1) AS hydro_ph,
        round(c1.hydro_ec_us_cm::numeric, 0) AS hydro_ec_us_cm,
        round(c1.hydro_tds_ppm::numeric, 0) AS hydro_tds_ppm,
        round(c1.hydro_water_temp_f::numeric, 1) AS hydro_water_temp_f
    FROM public.climate c1
    WHERE c1.hydro_ph IS NOT NULL
      AND c1.ts > now() - interval '30 minutes'
    ORDER BY c1.ts DESC
    LIMIT 1
) h ON true
CROSS JOIN public.v_cost_today cost
LEFT JOIN public.v_dli_current dc
  ON dc.greenhouse_id = COALESCE(c.greenhouse_id, 'vallery')
WHERE c.temp_avg IS NOT NULL
ORDER BY c.ts DESC
LIMIT 1;

COMMENT ON VIEW public.v_greenhouse_now IS
'Current greenhouse product view. dli_today is nullable and unavailable metadata is explicit while the interior sensor is invalid.';

