ALTER TABLE public.planner_lessons
    ADD CONSTRAINT planner_lessons_active_dli_proxy_block CHECK (
        is_active IS NOT TRUE
        OR NOT public.fn_dli_proxy_lesson_invalid(condition, lesson)
    );

CREATE OR REPLACE FUNCTION public.fn_search_embeddings(
    query_embedding vector(3072),
    p_top_k integer DEFAULT 10,
    p_source_types text[] DEFAULT ARRAY[
        'lesson', 'plan', 'site_doc', 'playbook', 'observation'
    ]
)
RETURNS TABLE (
    source_type text,
    source_id text,
    chunk_idx integer,
    content text,
    metadata jsonb,
    distance double precision
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT
        e.source_type,
        e.source_id,
        e.chunk_idx,
        e.content,
        e.metadata,
        (e.embedding <=> query_embedding)::double precision AS distance
    FROM public.verdify_embeddings e
    LEFT JOIN public.planner_lessons pl
      ON e.source_type = 'lesson'
     AND pl.id::text = e.source_id
    WHERE e.source_type = ANY(p_source_types)
      AND (
          e.source_type <> 'lesson'
          OR (
              pl.is_active IS TRUE
              AND pl.superseded_by IS NULL
              AND NOT public.fn_dli_proxy_lesson_invalid(
                  pl.condition,
                  pl.lesson
              )
          )
      )
    ORDER BY e.embedding <=> query_embedding
    LIMIT p_top_k;
END;
$$;

COMMENT ON FUNCTION public.fn_search_embeddings(vector, integer, text[]) IS
'Top-K semantic retrieval. Active lesson results also pass the DLI proxy/correction invalidation guard.';

-- This is the only view allowed to expose the old numeric proxy.  Its name and
-- evidence_class make the invalidity explicit; product consumers use
-- v_dli_current/v_dli_daily instead.
CREATE OR REPLACE VIEW public.v_dli_forensic_history AS
SELECT
    c.ts,
    COALESCE(c.greenhouse_id, 'vallery') AS greenhouse_id,
    c.dli_today AS forensic_proxy_dli_mol_m2_day,
    'forensic_invalid_proxy'::text AS evidence_class,
    COALESCE(v.availability, 'unavailable') AS availability,
    COALESCE(v.unavailable_reason, 'validity_contract_missing') AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to
FROM public.climate c
LEFT JOIN LATERAL public.fn_dli_validity(
    c.ts,
    COALESCE(c.greenhouse_id, 'vallery')
) v ON true
WHERE c.dli_today IS NOT NULL;

COMMENT ON VIEW public.v_dli_forensic_history IS
'Forensic-only legacy DLI proxy history. Numeric values came from an invalid interior sensor/exterior proxy/fixture estimate and must never be used as measured crop DLI.';

CREATE OR REPLACE VIEW public.v_dli_current AS
WITH latest AS (
    SELECT DISTINCT ON (COALESCE(c.greenhouse_id, 'vallery'))
        c.ts,
        COALESCE(c.greenhouse_id, 'vallery') AS greenhouse_id,
        c.dli_today AS forensic_proxy_dli_mol_m2_day
    FROM public.climate c
    ORDER BY COALESCE(c.greenhouse_id, 'vallery'), c.ts DESC
)
SELECT
    l.ts,
    l.greenhouse_id,
    NULL::double precision AS crop_dli_mol_m2_day,
    'unavailable'::text AS availability,
    CASE
        WHEN public.fn_dli_source_invalid_reason(
            l.forensic_proxy_dli_mol_m2_day
        ) IS NOT NULL
        THEN public.fn_dli_source_invalid_reason(
            l.forensic_proxy_dli_mol_m2_day
        )
        ELSE COALESCE(v.unavailable_reason, 'validity_contract_missing')
    END::text AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to,
    (l.forensic_proxy_dli_mol_m2_day IS NOT NULL) AS forensic_proxy_present
FROM latest l
LEFT JOIN LATERAL public.fn_dli_validity(l.ts, l.greenhouse_id) v ON true;

COMMENT ON VIEW public.v_dli_current IS
'Current interior crop DLI product contract. Migration 195 is categorically unavailable and always emits NULL. Invalid, non-finite, negative, missing, and out-of-range source readings receive explicit reasons; a later reviewed activation migration owns source completeness and calibration.';

CREATE OR REPLACE VIEW public.v_dli_daily AS
WITH day_bounds AS (
    SELECT
        ds.date,
        COALESCE(ds.greenhouse_id, 'vallery') AS greenhouse_id,
        ds.dli_final AS forensic_proxy_dli_mol_m2_day,
        ds.date::timestamp AT TIME ZONE 'America/Denver' AS day_start,
        (ds.date + 1)::timestamp AT TIME ZONE 'America/Denver' AS day_end
    FROM public.daily_summary ds
    WHERE ds.date IS NOT NULL
)
SELECT
    d.date,
    d.greenhouse_id,
    NULL::double precision AS crop_dli_mol_m2_day,
    'unavailable'::text AS availability,
    CASE
        WHEN d.day_end > now() THEN 'source_day_incomplete'
        WHEN public.fn_dli_source_invalid_reason(
            d.forensic_proxy_dli_mol_m2_day
        ) IS NOT NULL
        THEN public.fn_dli_source_invalid_reason(
            d.forensic_proxy_dli_mol_m2_day
        )
        ELSE COALESCE(v.unavailable_reason, 'validity_contract_missing')
    END::text AS unavailable_reason,
    COALESCE(v.provenance, 'unknown_unvalidated_source') AS provenance,
    COALESCE(v.validity_revision, 'missing') AS validity_revision,
    v.valid_from,
    v.valid_to,
    (d.forensic_proxy_dli_mol_m2_day IS NOT NULL) AS forensic_proxy_present
FROM day_bounds d
LEFT JOIN LATERAL public.fn_dli_validity(
    d.day_start + interval '12 hours',
    d.greenhouse_id
) v ON true;

COMMENT ON VIEW public.v_dli_daily IS
'Daily interior crop DLI product contract. Migration 195 is categorically unavailable and never emits a numeric value. A later reviewed sensor-activation migration must define source revision, cadence/completeness, calibration, and validity rules.';

