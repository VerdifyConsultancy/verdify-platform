-- 195-dli-availability-provenance.sql
--
-- Issue #435: interior crop DLI is unavailable while the interior light
-- sensor is broken.  Preserve legacy proxy values for forensic inspection,
-- but never promote them to measured crop evidence.
--
-- Non-self-transactional: safe for an outer rollback proof.

CREATE TABLE IF NOT EXISTS public.dli_validity_intervals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    greenhouse_id text NOT NULL DEFAULT 'vallery',
    valid_from timestamptz NOT NULL,
    valid_to timestamptz,
    availability text NOT NULL,
    unavailable_reason text,
    provenance text NOT NULL,
    validity_revision text NOT NULL,
    operator_validated boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text NOT NULL DEFAULT 'migration_195',
    CONSTRAINT dli_validity_interval_order CHECK (
        valid_to IS NULL OR valid_to > valid_from
    ),
    CONSTRAINT dli_validity_availability CHECK (
        availability IN ('available', 'unavailable')
    ),
    CONSTRAINT dli_validity_evidence_shape CHECK (
        (
            availability = 'available'
            AND operator_validated
            AND unavailable_reason IS NULL
        ) OR (
            availability = 'unavailable'
            AND NOT operator_validated
            AND unavailable_reason IS NOT NULL
            AND btrim(unavailable_reason) <> ''
        )
    ),
    CONSTRAINT dli_validity_revision_unique UNIQUE (
        greenhouse_id, validity_revision
    )
);

-- v195 is intentionally fail closed. This is an application/schema invariant,
-- not a privilege boundary: the production application role owns this table.
-- Enabling measured DLI therefore requires a separately reviewed migration
-- that removes/replaces this constraint and updates the product contract.
ALTER TABLE public.dli_validity_intervals
    DROP CONSTRAINT IF EXISTS dli_validity_release_unavailable;
ALTER TABLE public.dli_validity_intervals
    ADD CONSTRAINT dli_validity_release_unavailable CHECK (
        availability = 'unavailable'
        AND NOT operator_validated
    );

COMMENT ON TABLE public.dli_validity_intervals IS
'Fail-closed validity ledger for interior crop DLI. Migration 195 permits unavailable intervals only; ordinary DML cannot activate DLI. Future activation requires a separately reviewed migration/contract change. This is a schema invariant, not DB-role privilege separation.';

CREATE OR REPLACE FUNCTION public.enforce_dli_validity_nonoverlap()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.dli_validity_intervals existing
        WHERE existing.greenhouse_id = NEW.greenhouse_id
          AND existing.id <> COALESCE(NEW.id, -1)
          AND tstzrange(
                existing.valid_from,
                COALESCE(existing.valid_to, 'infinity'::timestamptz),
                '[)'
              ) && tstzrange(
                NEW.valid_from,
                COALESCE(NEW.valid_to, 'infinity'::timestamptz),
                '[)'
              )
    ) THEN
        RAISE EXCEPTION
            'DLI validity interval overlaps an existing interval for greenhouse %',
            NEW.greenhouse_id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_dli_validity_nonoverlap
    ON public.dli_validity_intervals;
CREATE TRIGGER trg_dli_validity_nonoverlap
BEFORE INSERT OR UPDATE ON public.dli_validity_intervals
FOR EACH ROW EXECUTE FUNCTION public.enforce_dli_validity_nonoverlap();

-- The legacy accumulator has never been backed by an operator-validated
-- interior sensor.  Start before recorded production history so every legacy
-- row is classified without rewriting or deleting its numeric proxy value.
INSERT INTO public.dli_validity_intervals (
    greenhouse_id,
    valid_from,
    valid_to,
    availability,
    unavailable_reason,
    provenance,
    validity_revision,
    operator_validated,
    created_by
) SELECT
    'vallery',
    '2024-01-01 00:00:00+00',
    NULL,
    'unavailable',
    'interior_light_sensor_broken',
    'legacy_invalid_exterior_proxy_plus_fixture_estimate',
    'dli-validity-v1',
    false,
    'migration_195'
WHERE NOT EXISTS (
    SELECT 1
    FROM public.dli_validity_intervals existing
    WHERE existing.greenhouse_id = 'vallery'
      AND existing.validity_revision = 'dli-validity-v1'
);

CREATE OR REPLACE FUNCTION public.fn_dli_validity(
    p_ts timestamptz DEFAULT now(),
    p_greenhouse_id text DEFAULT 'vallery'
)
RETURNS TABLE (
    availability text,
    unavailable_reason text,
    provenance text,
    validity_revision text,
    valid_from timestamptz,
    valid_to timestamptz,
    operator_validated boolean
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        v.availability,
        v.unavailable_reason,
        v.provenance,
        v.validity_revision,
        v.valid_from,
        v.valid_to,
        v.operator_validated
    FROM public.dli_validity_intervals v
    WHERE v.greenhouse_id = p_greenhouse_id
      AND p_ts >= v.valid_from
      AND (v.valid_to IS NULL OR p_ts < v.valid_to)
    ORDER BY v.valid_from DESC
    LIMIT 1
$$;

COMMENT ON FUNCTION public.fn_dli_validity(timestamptz, text) IS
'Returns the one half-open validity interval governing interior crop DLI at a timestamp. Under migration 195 every returned interval is unavailable; no row means no DLI contract exists.';

CREATE OR REPLACE FUNCTION public.fn_dli_source_invalid_reason(
    p_value double precision
)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_value IS NULL THEN
        RETURN 'source_reading_missing';
    ELSIF p_value::text IN ('NaN', 'Infinity', '-Infinity') THEN
        RETURN 'source_reading_nonfinite';
    ELSIF p_value < 0 THEN
        RETURN 'source_reading_negative';
    ELSIF p_value > 100 THEN
        RETURN 'source_reading_out_of_range';
    END IF;
    RETURN NULL;
END;
$$;

COMMENT ON FUNCTION public.fn_dli_source_invalid_reason(double precision) IS
'Returns an explicit reason when candidate interior DLI is missing, non-finite, negative, or outside the 0..100 mol/m2/day product range.';

CREATE OR REPLACE FUNCTION public.fn_dli_proxy_lesson_invalid(
    p_condition text,
    p_lesson text
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
    WITH normalized AS (
        SELECT lower(
            COALESCE(p_condition, '') || ' ' || COALESCE(p_lesson, '')
        ) AS body
    )
    SELECT
        body ~ '(sensor[_ -]*dli|dli[_ -]*(today|sensor)|interior[^.]{0,40}dli|crop[^.]{0,40}dli)'
        AND (
            body ~ '(×|[*]|[[:space:]]x[[:space:]])[[:space:]]*[0-9]'
            OR body ~ '(correction|corrected|proxy|estimate|estimated|multiply|multiplied|factor)'
            OR body ~ 'grow[_ -]*light[_ -]*(hours|runtime)'
        )
    FROM normalized
$$;

COMMENT ON FUNCTION public.fn_dli_proxy_lesson_invalid(text, text) IS
'Matches operational lessons that infer interior/crop DLI from the invalid sensor, a correction factor, proxy, estimate, or grow-light runtime.';

