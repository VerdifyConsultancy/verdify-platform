-- 195-dli-availability-provenance.sql
--
-- Issue #435: interior crop DLI is unavailable while the interior light
-- sensor is broken.  Preserve legacy proxy values for forensic inspection,
-- but never promote them to measured crop evidence.
--
-- Non-self-transactional: safe for an outer rollback proof.

CREATE TABLE IF NOT EXISTS public.dli_validity_intervals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    greenhouse_id text NOT NULL DEFAULT 'vallery',
    valid_from timestamptz NOT NULL,
    valid_to timestamptz,
    availability text NOT NULL,
    unavailable_reason text,
    provenance text NOT NULL,
    validity_revision text NOT NULL,
    operator_validated boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text NOT NULL DEFAULT 'migration_195',
    CONSTRAINT dli_validity_interval_order CHECK (
        valid_to IS NULL OR valid_to > valid_from
    ),
    CONSTRAINT dli_validity_availability CHECK (
        availability IN ('available', 'unavailable')
    ),
    CONSTRAINT dli_validity_evidence_shape CHECK (
        (
            availability = 'available'
            AND operator_validated
            AND unavailable_reason IS NULL
        ) OR (
            availability = 'unavailable'
            AND NOT operator_validated
            AND unavailable_reason IS NOT NULL
            AND btrim(unavailable_reason) <> ''
        )
    ),
    CONSTRAINT dli_validity_revision_unique UNIQUE (
        greenhouse_id, validity_revision
    )
);

COMMENT ON TABLE public.dli_validity_intervals IS
'Operator-controlled validity ledger for interior crop DLI. Available intervals require explicit operator validation; unavailable intervals carry reason, provenance, revision, and half-open validity bounds.';

CREATE OR REPLACE FUNCTION public.enforce_dli_validity_nonoverlap()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.dli_validity_intervals existing
        WHERE existing.greenhouse_id = NEW.greenhouse_id
          AND existing.id <> COALESCE(NEW.id, -1)
          AND tstzrange(
                existing.valid_from,
                COALESCE(existing.valid_to, 'infinity'::timestamptz),
                '[)'
              ) && tstzrange(
                NEW.valid_from,
                COALESCE(NEW.valid_to, 'infinity'::timestamptz),
                '[)'
              )
    ) THEN
        RAISE EXCEPTION
            'DLI validity interval overlaps an existing interval for greenhouse %',
            NEW.greenhouse_id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_dli_validity_nonoverlap
    ON public.dli_validity_intervals;
CREATE TRIGGER trg_dli_validity_nonoverlap
BEFORE INSERT OR UPDATE ON public.dli_validity_intervals
FOR EACH ROW EXECUTE FUNCTION public.enforce_dli_validity_nonoverlap();

