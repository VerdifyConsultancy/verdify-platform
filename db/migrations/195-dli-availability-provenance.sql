-- Product KPI retains its established column order and score semantics.  The
-- old dli column remains for compatibility but is NULL; appended fields carry
-- the reason/provenance/valid interval.
CREATE OR REPLACE VIEW public.v_daily_kpi AS
WITH evidence AS (
    SELECT
        d.*,
        w.quality_filtered_meter_gal,
        w.climate_wetting_gal,
        COALESCE(w.available_for_scoring, false) AS water_ok,
        e.modeled_kwh,
        COALESCE(e.available_for_scoring, false) AS energy_ok,
        dl.crop_dli_mol_m2_day,
        dl.availability AS dli_availability,
        dl.unavailable_reason AS dli_unavailable_reason,
        dl.provenance AS dli_provenance,
        dl.validity_revision AS dli_validity_revision,
        dl.valid_from AS dli_valid_from,
        dl.valid_to AS dli_valid_to
    FROM public.daily_summary d
    LEFT JOIN public.v_water_attribution_daily w
      ON w.date = d.date AND w.greenhouse_id = d.greenhouse_id
    LEFT JOIN public.v_runtime_energy_daily e
      ON e.date = d.date AND e.greenhouse_id = d.greenhouse_id
    LEFT JOIN public.v_dli_daily dl
      ON dl.date = d.date
     AND dl.greenhouse_id = COALESCE(d.greenhouse_id, 'vallery')
    WHERE d.date IS NOT NULL
), normalized AS (
    SELECT
        e.*,
        COALESCE(e.compliance_v2_attributable_pct, e.compliance_pct, 0)
            AS score_compliance,
        e.water_ok AND e.energy_ok AND e.cost_total IS NOT NULL AS resource_ok
    FROM evidence e
)
SELECT
    date,
    round(score_compliance::numeric, 1) AS compliance_pct,
    round(COALESCE(graded_temp_compliance_pct, temp_compliance_pct, 0)::numeric, 1)
        AS temp_compliance_pct,
    round(COALESCE(graded_vpd_compliance_pct, vpd_compliance_pct, 0)::numeric, 1)
        AS vpd_compliance_pct,
    round(COALESCE(graded_stress_hours_heat, stress_hours_heat, 0)::numeric, 2)
        AS heat_stress_h,
    round(COALESCE(graded_stress_hours_cold, stress_hours_cold, 0)::numeric, 2)
        AS cold_stress_h,
    round(COALESCE(graded_stress_hours_vpd_high, stress_hours_vpd_high, 0)::numeric, 2)
        AS vpd_high_stress_h,
    round(COALESCE(graded_stress_hours_vpd_low, stress_hours_vpd_low, 0)::numeric, 2)
        AS vpd_low_stress_h,
    round((
        COALESCE(graded_stress_hours_heat, stress_hours_heat, 0)
        + COALESCE(graded_stress_hours_cold, stress_hours_cold, 0)
        + COALESCE(graded_stress_hours_vpd_high, stress_hours_vpd_high, 0)
        + COALESCE(graded_stress_hours_vpd_low, stress_hours_vpd_low, 0)
    )::numeric, 2) AS total_stress_h,
    CASE WHEN energy_ok THEN round(modeled_kwh::numeric, 2) END AS kwh,
    CASE WHEN resource_ok
      THEN round(COALESCE(therms_estimated, gas_used_therms)::numeric, 3)
    END AS therms,
    CASE WHEN water_ok THEN round(quality_filtered_meter_gal::numeric, 0) END AS water_gal,
    CASE WHEN water_ok THEN round(climate_wetting_gal::numeric, 0) END AS mister_water_gal,
    CASE WHEN energy_ok THEN round(cost_electric::numeric, 2) END AS cost_electric,
    CASE WHEN resource_ok THEN round(cost_gas::numeric, 2) END AS cost_gas,
    CASE WHEN water_ok THEN round(cost_water::numeric, 2) END AS cost_water,
    CASE WHEN resource_ok THEN round(cost_total::numeric, 2) END AS cost_total,
    round(temp_min::numeric, 1) AS temp_min,
    round(temp_max::numeric, 1) AS temp_max,
    round(temp_avg::numeric, 1) AS temp_avg,
    round(vpd_min::numeric, 2) AS vpd_min,
    round(vpd_max::numeric, 2) AS vpd_max,
    round(vpd_avg::numeric, 2) AS vpd_avg,
    round(crop_dli_mol_m2_day::numeric, 1) AS dli,
    round(min_dp_margin_f::numeric, 1) AS dp_margin_min_f,
    round(COALESCE(dp_risk_hours, 0)::numeric, 1) AS dp_risk_hours,
    round((CASE
        WHEN resource_ok THEN score_compliance / 100.0 * 80
          + GREATEST(0, 1.0 - LEAST(cost_total / 15.0, 1.0)) * 20
        ELSE score_compliance
    END)::numeric, 1) AS planner_score,
    CASE WHEN resource_ok THEN 20::numeric ELSE 0::numeric END
        AS planner_score_resource_weight_pct,
    resource_ok AS resource_terms_available,
    dli_availability,
    dli_unavailable_reason,
    dli_provenance,
    dli_validity_revision,
    dli_valid_from,
    dli_valid_to
FROM normalized
ORDER BY date;

COMMENT ON VIEW public.v_daily_kpi IS
'Daily planner KPI with provenance-gated resources and availability-bearing crop DLI. Invalid interior-light evidence remains NULL and has zero score influence.';

CREATE OR REPLACE VIEW public.v_iris_planning_context AS
SELECT
    now() AS query_ts,
    (
        SELECT json_build_object(
            'temp_avg', round(avg(c.temp_avg)::numeric, 1),
            'vpd_avg', round(avg(c.vpd_avg)::numeric, 2),
            'rh_avg', round(avg(c.rh_avg)::numeric, 1),
            'outdoor_temp_f', round(avg(c.outdoor_temp_f)::numeric, 1),
            'dli', (
                SELECT json_build_object(
                    'value_mol_m2_day', dc.crop_dli_mol_m2_day,
                    'availability', dc.availability,
                    'unavailable_reason', dc.unavailable_reason,
                    'provenance', dc.provenance,
                    'validity_revision', dc.validity_revision,
                    'valid_from', dc.valid_from,
                    'valid_to', dc.valid_to
                )
                FROM public.v_dli_current dc
                WHERE dc.greenhouse_id = 'vallery'
                LIMIT 1
            ),
            'co2_ppm', round(avg(c.co2_ppm)::numeric, 0)
        )
        FROM public.climate c
        WHERE c.ts >= now() - interval '1 hour'
          AND c.temp_avg IS NOT NULL
    ) AS current_conditions,
    (
        SELECT json_build_object(
            'north', round(avg(c.temp_north)::numeric, 1),
            'south', round(avg(c.temp_south)::numeric, 1),
            'east', round(avg(c.temp_east)::numeric, 1),
            'west', round(avg(c.temp_west)::numeric, 1)
        )
        FROM public.climate c
        WHERE c.ts >= now() - interval '1 hour'
          AND c.temp_avg IS NOT NULL
    ) AS zone_context,
    (
        SELECT json_build_object(
            'date', ds.date,
            'cost_total', ds.cost_total,
            'dli', json_build_object(
                'value_mol_m2_day', d.crop_dli_mol_m2_day,
                'availability', d.availability,
                'unavailable_reason', d.unavailable_reason,
                'provenance', d.provenance,
                'validity_revision', d.validity_revision,
                'valid_from', d.valid_from,
                'valid_to', d.valid_to
            ),
            'stress_hours_vpd_high', ds.stress_hours_vpd_high,
            'water_used_gal', ds.water_used_gal
        )
        FROM public.daily_summary ds
        LEFT JOIN public.v_dli_daily d
          ON d.date = ds.date
         AND d.greenhouse_id = COALESCE(ds.greenhouse_id, 'vallery')
        ORDER BY ds.date DESC
        LIMIT 1
    ) AS yesterday_summary,
    json_build_object(
        'value_mol_m2_day', NULL,
        'availability', 'unavailable',
        'unavailable_reason', 'no_valid_interior_light_sensor',
        'provenance', 'outdoor_forecast_is_not_interior_crop_dli',
        'validity_revision', 'dli-validity-v1',
        'valid_from', '2024-01-01T00:00:00Z',
        'valid_to', NULL
    ) AS dli_forecast,
    (
        SELECT json_object_agg(sub.parameter, sub.value)
        FROM (
            SELECT DISTINCT ON (s.parameter) s.parameter, s.value
            FROM public.setpoint_changes s
            ORDER BY s.parameter, s.ts DESC
        ) sub
    ) AS current_setpoints,
    (
        SELECT json_agg(row_to_json(sub.*) ORDER BY sub.ts)
        FROM (
            SELECT p.ts, p.parameter, p.value, p.reason
            FROM public.setpoint_plan p
            WHERE p.ts > now()
              AND p.is_active
              AND p.parameter <> 'plan_metadata'
            ORDER BY p.ts
        ) sub
    ) AS active_plan,
    (
        SELECT json_build_object(
            'composite_score', public.fn_system_health(),
            'components', (
                SELECT json_agg(json_build_object(
                    'component', h.component,
                    'score', h.score_pct
                ))
                FROM public.v_system_health_score h
            )
        )
    ) AS system_health,
    json_build_object(
        'electric_per_kwh', 0.111,
        'gas_per_therm', 0.83,
        'water_per_gal', 0.00484
    ) AS cost_rates;

COMMENT ON VIEW public.v_iris_planning_context IS
'Single-query Iris context with availability-bearing DLI. No outdoor forecast or legacy proxy is presented as measured interior crop light.';

CREATE OR REPLACE VIEW public.v_water_efficiency AS
SELECT
    ds.date,
    ds.water_used_gal,
    d.crop_dli_mol_m2_day AS dli_final,
    CASE
        WHEN d.crop_dli_mol_m2_day > 0
        THEN round((ds.water_used_gal / d.crop_dli_mol_m2_day)::numeric, 3)
    END AS gal_per_mol_dli,
    d.availability AS dli_availability,
    d.unavailable_reason AS dli_unavailable_reason,
    d.provenance AS dli_provenance,
    d.validity_revision AS dli_validity_revision,
    d.valid_from AS dli_valid_from,
    d.valid_to AS dli_valid_to
FROM public.daily_summary ds
LEFT JOIN public.v_dli_daily d
  ON d.date = ds.date
 AND d.greenhouse_id = COALESCE(ds.greenhouse_id, 'vallery')
WHERE ds.water_used_gal IS NOT NULL
ORDER BY ds.date;

COMMENT ON VIEW public.v_water_efficiency IS
'Water/DLI efficiency remains unavailable while crop DLI is unavailable; water evidence stays independently visible.';
